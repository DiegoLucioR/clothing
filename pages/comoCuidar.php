    <h1>cuide bem de <br> seus básicos</h1>
    <p>instruções de lavagem que farão com que suas roupas te acompanhem por muito mais tempo.</p>

    <h2>pré lavagem</h2>
    <ol>
        <li>mantenha a roupa seca e arejada antes de lavá-la para evitar mofo.</li>
        <li>esvazie os bolsos das roupas.</li>
        <li>abotoe, feche os zíperes de calças e levante a gola das camisas.</li>
        <li>separe as peças mais sujas e/ou manchadas das que estão menos sujas.</li>
    </ol>

    <h2>lavagem</h2>
    <ol>
        <li>ideal utilizar sempre saquinhos próprios para embalar as roupas finas ao lavar em máquina.</li>
        <li>se você está inseguro, lave na temperatura mais baixa, no modo mais ameno e não centrifugue.</li>
        <li>use apenas a metade do detergente recomendado, sua roupa vai ficar limpa e durar o dobro - além de ajudar o planeta.</li>
        <li>ao colocar de molho, a duração deve ser de no máximo 60 minutos.</li>
    </ol>

    <h2>secagem</h2>
    <ol>
        <li>secar as peças em cabide evita marcas de prendedores e facilita a passadoria.</li>
        <li>não torça as peças.</li>
        <li>não coloque as peças para secar ao sol. o correto é secar à sombra, em local fresco e ventilado.</li>
    </ol>

    <h2>outras dicas</h2>
    <ol>
        <li>na hora de passar, sempre coloque uma proteção entre o tecido e a chapa do ferro.</li>
        <li>para saber se sua peça vai soltar tinta, faça o teste: umedeça um pedaço da roupa (recomendamos a barra/bainha) e passe ferro com um tecido branco sobre a área umedecida. se a cor da peça ficar no tecido, lave-a separadamente.</li>
        <li>leia atentamente as instruções de cuidado nas etiquetas de suas roupas, isso fará com que elas durem muito mais.</li>
    </ol>
